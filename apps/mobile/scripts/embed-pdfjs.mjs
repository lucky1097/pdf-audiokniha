// Embeds pdf.js (library and worker) as strings, so the PDF reader WebView works offline without a CDN, and
// core's markUnknownGlyphs() (fixes Safari's broken character maps before pdf.js reads the file).
// Runs on install (also on EAS Build); the output is generated and gitignored.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
// The legacy build: WebKit (the iPhone WebView) lacks newer features the default build assumes.
const dist = join(dirname(require.resolve("pdfjs-dist/package.json")), "legacy", "build");
const lib = readFileSync(join(dist, "pdf.min.mjs"), "utf8");
const worker = readFileSync(join(dist, "pdf.worker.min.mjs"), "utf8");

// tounicode.ts is self-contained; bundled as a script that sets window.AudioknihaGlyphs.
const bundle = await rolldown({ input: join(here, "..", "..", "..", "packages", "core", "src", "pdf", "tounicode.ts"), logLevel: "warn" });
const glyphs = (await bundle.generate({ format: "iife", name: "AudioknihaGlyphs" })).output[0].code;
await bundle.close();

const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "pdfjs.ts"),
  `// Generated by scripts/embed-pdfjs.mjs from pdfjs-dist and packages/core; do not edit.\nexport const PDFJS_LIB = ${JSON.stringify(lib)};\nexport const PDFJS_WORKER = ${JSON.stringify(worker)};\nexport const GLYPHS = ${JSON.stringify(glyphs)};\n`,
);
console.log(`embed-pdfjs: ${Math.round((lib.length + worker.length) / 1024)} KB, glyph fix ${Math.round(glyphs.length / 1024)} KB`);
