// Embeds pdf.js (library and worker) as strings, so the PDF reader WebView works offline without a CDN.
// Runs on install (also on EAS Build); the output is generated and gitignored.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const dist = join(dirname(require.resolve("pdfjs-dist/package.json")), "build");
const lib = readFileSync(join(dist, "pdf.min.mjs"), "utf8");
const worker = readFileSync(join(dist, "pdf.worker.min.mjs"), "utf8");
const out = join(here, "..", "src", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, "pdfjs.ts"),
  `// Generated by scripts/embed-pdfjs.mjs from pdfjs-dist; do not edit.\nexport const PDFJS_LIB = ${JSON.stringify(lib)};\nexport const PDFJS_WORKER = ${JSON.stringify(worker)};\n`,
);
console.log(`embed-pdfjs: ${Math.round((lib.length + worker.length) / 1024)} KB`);
