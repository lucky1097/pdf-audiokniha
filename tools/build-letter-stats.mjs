// Builds packages/core/src/pdf/letter-stats.ts: how often each three-letter sequence occurs inside words, per
// language. glyphs.ts uses it to tell which ligature a broken glyph stood for ("hrms": firms, not flrms).
// Only counts are kept, no text. Sources used for the committed file (2026-11-09): English, Project Gutenberg
// #1342 (public domain) and Wikipedia articles on economics and technology; Slovak, Wikipedia articles.
// Usage: node tools/build-letter-stats.mjs <dir with en*.txt and sk*.txt files>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2];
const out = {};
for (const lang of ["en", "sk"]) {
  const text = readdirSync(dir)
    .filter((f) => f.startsWith(lang) || f.startsWith(`wiki-${lang}`))
    .map((f) => readFileSync(join(dir, f), "utf8"))
    .join("\n")
    .toLowerCase();
  const counts = new Map();
  let words = 0;
  for (const w of text.match(/\p{L}+/gu) ?? []) {
    words++;
    const s = `^${w}$`;
    for (let i = 0; i + 3 <= s.length; i++) counts.set(s.slice(i, i + 3), (counts.get(s.slice(i, i + 3)) ?? 0) + 1);
  }
  const kept = [...counts].filter(([, n]) => n >= 2).sort((a, b) => b[1] - a[1]);
  out[lang] = kept.map(([t, n]) => `${t}${n.toString(36)}`).join(",");
  console.log(lang, "words", words, "trigrams", counts.size, "kept", kept.length, "chars", out[lang].length);
}
writeFileSync(
  new URL("../packages/core/src/pdf/letter-stats.ts", import.meta.url),
  `// Generated by tools/build-letter-stats.mjs; do not edit. Three letters (^ and $ mark word edges), then the count in base 36.\nexport const LETTER_STATS: Record<"en" | "sk", string> = ${JSON.stringify(out, null, 2)};\n`,
);
