// Builds packages/core/src/sk-words.ts: Slovak words with ť, ľ, ď that a photographed page often loses the háček of
// ("robit" for "robiť"). Only forms whose plain spelling is not a Slovak word are kept, so real words (byt, celkom,
// hotel, list) never change. Built 2026-11-20.
// Sources: Leipzig Corpora Collection, slk_newscrawl_2016_1M word counts (CC BY 4.0, licenses/leipzig-corpora-CC-BY-4.0.txt);
// Slovak hunspell dictionary sk_SK.aff/.dic, sk-spell/hunspell-sk (MPL-2.0, licenses/hunspell-sk-MPL-2.0.txt).
// The dictionary is read with nspell 2.1.5 (MIT), used only by this tool.
// Usage: node tools/build-sk-words.mjs <words.txt> <sk_SK.aff> <sk_SK.dic>
import { readFileSync, writeFileSync } from "node:fs";
import nspell from "nspell";

const MIN_COUNT = 3;
// Forms this common in edited news text are real even when the dictionary lacks them (adverb ľahko, count 827).
const CORPUS_ONLY_MIN = 100;
// A plain spelling this common in the corpus is a real word or a name, e.g. "pod" 12790 vs "poď" 18. Real
// dropped-háček typos stay below this ratio (robit 734 vs robiť 2944 = 0.25).
const PLAIN_REAL_RATIO = 0.5;
const AMBIGUOUS_RATIO = 1 / 3;
const [wordsPath, affPath, dicPath] = process.argv.slice(2);

const spell = nspell({ aff: readFileSync(affPath), dic: readFileSync(dicPath) });
const accepted = (w) => spell.correct(w) || spell.correct(w[0].toUpperCase() + w.slice(1));

const STRIP = { "ť": "t", "ľ": "l", "ď": "d" };
const strip = (w) => w.replace(/[ťľď]/g, (c) => STRIP[c]);

// Counts per lowercase word; lines are "id<TAB>word<TAB>count".
const counts = new Map();
for (const line of readFileSync(wordsPath, "utf8").split("\n")) {
  const [, word, n] = line.split("\t");
  if (!word || !/^\p{L}+$/u.test(word)) continue;
  const w = word.toLowerCase();
  counts.set(w, (counts.get(w) ?? 0) + Number(n));
}

// Every variant made by stripping a non-empty subset of the ť/ľ/ď letters of w.
function plainVariants(w) {
  const special = [...w].map((c, i) => (c in STRIP ? i : -1)).filter((i) => i >= 0);
  const out = [];
  for (let mask = 1; mask < 1 << special.length; mask++) {
    const chars = [...w];
    special.forEach((pos, k) => {
      if (mask & (1 << k)) chars[pos] = STRIP[chars[pos]];
    });
    out.push(chars.join(""));
  }
  return out;
}

const candidates = [...counts]
  .filter(([w, n]) => n >= MIN_COUNT && /[ťľď]/.test(w) && (accepted(w) || n >= CORPUS_ONLY_MIN))
  .filter(([w]) => !plainVariants(w).some(accepted))
  .filter(([w, n]) => !plainVariants(w).some((v) => (counts.get(v) ?? 0) >= PLAIN_REAL_RATIO * n));
const corpusOnly = candidates.filter(([w]) => !accepted(w)).length;

// Group by plain spelling; keep the most frequent form unless another form is nearly as frequent.
const groups = new Map();
for (const [w, n] of candidates) {
  const key = strip(w);
  groups.set(key, [...(groups.get(key) ?? []), [w, n]]);
}
const kept = [];
for (const forms of groups.values()) {
  forms.sort((a, b) => b[1] - a[1]);
  if (forms.length > 1 && forms[1][1] >= forms[0][1] * AMBIGUOUS_RATIO) continue;
  kept.push(forms[0]);
}
kept.sort((a, b) => b[1] - a[1]);

const list = kept.map(([w]) => w).join(" ");
writeFileSync(
  new URL("../packages/core/src/sk-words.ts", import.meta.url),
  `// Generated by tools/build-sk-words.mjs; do not edit. Slovak words with ť, ľ, ď, most frequent first. Sources: Leipzig Corpora Collection slk_newscrawl_2016_1M (CC BY 4.0) and the sk-spell/hunspell-sk dictionary (MPL-2.0); see licenses/.\nexport const SK_HACEK_WORDS = ${JSON.stringify(list)};\n`,
);
console.log(`corpus-only ${corpusOnly}`);
console.log(`forms ${kept.length} chars ${list.length}`);
